function Format-Elapsed([timespan]$ts){
  if ($ts.TotalHours -ge 1) { return ('{0}h {1:d2}m' -f [int][math]::Floor($ts.TotalHours), $ts.Minutes) }
  return ('{0:d2}:{1:d2}' -f $ts.Minutes, $ts.Seconds)
}
