while (-not $stopReq -and ($DurationHours -le 0 -or (Get-Date) -lt $end)) {
  $tickStart = Get-Date
  $tick = [ordered]@{ t = $tickStart.ToString('o') }

  # connectivity: gateway (local hop) + internet IPs, each a burst of pings
  $q = [ordered]@{}
  if ($gateway) { $r = Test-PingSet $gateway $PingCount 1000; $q['gw'] = $r; $tick.gw = $(if ($r.recv) { $r.avg } else { -1 }) } else { $tick.gw = $null }
  foreach ($tg in $targets) { $r = Test-PingSet $tg $PingCount 1000; $q[$tg] = $r; $tick[$tg] = $(if ($r.recv) { $r.avg } else { -1 }) }
  $tick.q = $q

  # DNS resolution time (-DnsOnly: force a real query, not the local cache)
  $sw = [System.Diagnostics.Stopwatch]::StartNew()
  if ($script:hasResolve) { $rr = Resolve-DnsName -Name $dnsHost -Type A -DnsOnly -ErrorAction SilentlyContinue }
  else { $rr = $null; try { $rr = [System.Net.Dns]::GetHostAddresses($dnsHost) } catch {} }
  $sw.Stop()
  $tick.dns = $(if ($rr) { [int]$sw.Elapsed.TotalMilliseconds } else { -1 })

  # Wi-Fi link detail
  $w = Get-WlanInfo
  $tick.ssid=$w.ssid; $tick.sig=$w.sig; $tick.bssid=$w.bssid; $tick.band=$w.band; $tick.chan=$w.chan; $tick.rx=$w.rx; $tick.tx=$w.tx; $tick.radio=$w.radio

  # periodic channel-congestion scan
  if ($nbrEvery -gt 0 -and $w.chan -and ($k % $nbrEvery -eq 0)) { $tick.nbr = Get-Congestion $w.chan }
  $k++

  # adapters up + wired link speed ($null = could not enumerate; do not read that as "down")
  $allAd = @(Get-NetAdapter -ErrorAction SilentlyContinue)
  $ups = @($allAd | Where-Object { $_.Status -eq 'Up' })
  $tick.up = $(if ($allAd.Count -eq 0) { $null } else { [bool]$ups.Count })
  $eth = Get-EthMbps $ups
  if ($eth -ne $null) { $tick.eth = $eth }

  # Windows Wi-Fi events since last tick (disconnect reasons etc.)
  $wev = @(Get-WlanEvents $stLastEvT)
  $stLastEvT = $tickStart
  if ($wev.Count) { $tick.wlanEv = @($wev) }

  # sites (@() keeps a single result an array through ConvertTo-Json)
  if ($httpTargets.Count) { $tick.http = @(Test-Sites $httpTargets) } else { $tick.http = @() }

  # A full outage needs more evidence than ICMP alone: some networks block ping
  # while normal traffic keeps working. Only downgrade a ping failure when
  # something else actually crossed the internet in the same tick - an off-LAN
  # DNS answer, or a watched site responding. An on-prem resolver answering
  # proves nothing (it is reachable over the LAN during an internet outage).
  $reach = @($targets | ForEach-Object { $tick[$_] } | Where-Object { $_ -ge 0 }).Count
  $dnsProof  = $dnsIsPublic -and ($tick.dns -ge 0)
  $siteProof = [bool](@($tick.http | Where-Object { $_.ms -ge 0 }).Count)
  $isDown = ($tick.up -eq $false) -or (($reach -eq 0) -and -not $dnsProof -and -not $siteProof)
  $icmpOnly = ($reach -eq 0) -and -not $isDown
  $tick.down = [bool]$isDown
  $tick.icmpOnly = [bool]$icmpOnly
  if ($isDown -and -not $stWasDown -and ((Get-Date) - $stLastTrace).TotalSeconds -gt 300) {
    $tick.trace = @(Invoke-QuickTrace '1.1.1.1' 6)
    $stLastTrace = Get-Date
  }

  $tickEnd = Get-Date
  $tick.tEnd = $tickEnd.ToString('o')
  $tick.elapsedMs = [int][math]::Round(($tickEnd - $tickStart).TotalMilliseconds)
  $tickJson = $tick | ConvertTo-Json -Compress -Depth 6
  $script:logLines.Add($tickJson)
  Add-Content -Path $out -Value $tickJson -Encoding utf8

  # ---------- session stats + status ----------
  $i1 = $q['1.1.1.1']
  $loss = if ($i1) { $i1.loss } else { 100 }
  $jit  = if ($i1 -and $i1.jit -ne $null) { $i1.jit } else { 0 }
  if ($isDown) {
    if (-not $stWasDown) { $stOutages++; Add-Ev ($tickStart.ToString('HH:mm:ss') + ' DOWN') }
    $stDownSec += $IntervalSec
  } elseif ($stWasDown) { Add-Ev ($tickStart.ToString('HH:mm:ss') + ' back up') }
  $stWasDown = $isDown
  if (-not $isDown -and -not $icmpOnly -and $loss -gt 0) { $stLoss++ }
  if (-not $isDown -and $jit -ge 30) { $stJit++ }
  if ($tick.dns -lt 0) { $stDnsFail++; if (-not $isDown) { Add-Ev ($tickStart.ToString('HH:mm:ss') + ' DNS failed') } }
  if ($w.bssid) {
    if ($script:prevBssid -and $w.bssid -ne $script:prevBssid) { $stRoams++; Add-Ev ($tickStart.ToString('HH:mm:ss') + ' roamed to ' + $w.bssid) }
    [void]$stAps.Add($w.bssid)
    $script:prevBssid = $w.bssid
  }
  foreach ($e in $wev) { if ($e.id -eq 8003) { Add-Ev (([datetime]$e.t).ToString('HH:mm:ss') + ' ' + $e.msg) } }

  $state = if ($isDown) { 'DOWN' } elseif ($icmpOnly) { 'ICMP?' } elseif ($tick.dns -lt 0) { 'DNS!' } elseif ($loss -gt 0) { 'LOSS' } elseif ($jit -ge 30) { 'JIT' } else { 'ok' }
  $c = '.'; if ($state -eq 'DOWN') { $c = 'x' } elseif ($state -ne 'ok') { $c = '!' }
  $stHist += $c; if ($stHist.Length -gt 400) { $stHist = $stHist.Substring($stHist.Length - 400) }

  if ($interactive) {
    $sitesStr = '-'
    if ($tick.http.Count) { $sitesStr = (@($tick.http | ForEach-Object { $h=[System.Uri]$_.u; $h.Host + ' ' + $(if ($_.ms -lt 0) { 'DOWN' } else { [string]$_.ms + 'ms' }) }) -join '   ') }
    Draw-Dash @{
      hostName = $env:COMPUTERNAME
      interval = $IntervalSec
      elapsed = Format-Elapsed ((Get-Date) - $startT)
      n = $k
      state = $state
      ping = $(if ($tick.'1.1.1.1' -ge 0) { [string]$tick.'1.1.1.1' + ' ms' } else { '--' })
      loss = ([string]$loss + '%'); lossVal = $loss
      jit  = ([string]$jit + ' ms'); jitVal = $jit
      dns  = $(if ($tick.dns -ge 0) { [string]$tick.dns + ' ms' } else { 'FAIL' })
      gw   = $(if ($gateway) { $(if ($tick.gw -ge 0) { [string]$tick.gw + ' ms' } else { 'DOWN' }) } else { 'n/a' })
      wifi = ($w.sig -ne $null)
      ssid = $(if ($w.ssid) { $w.ssid } else { '-' })
      sig  = $(if ($w.sig -ne $null) { [string]$w.sig + '%' } else { '-' }); sigVal = $w.sig
      band = $(if ($w.band) { $w.band + '  ch' + $w.chan } else { '-' })
      rate = $(if ($w.rx -ne $null) { [string]$w.rx + ' Mbps' } else { '-' })
      link = $(if ($eth -ne $null) { 'wired  ' + $eth + ' Mbps' } else { 'no link' })
      ap   = $(if ($w.bssid) { $w.bssid } elseif ($bssidHidden) { 'hidden (Location off)' } else { '-' })
      roams = $stRoams; aps = $stAps.Count
      sites = $sitesStr
      hist = $stHist
      outages = [string]$stOutages; outagesN = $stOutages; downDur = ([string]$stDownSec + 's')
      lossN = [string]$stLoss; jitN = [string]$stJit; dnsN = [string]$stDnsFail
      events = @($stEvents)
      logPath = $out
    }
  } else {
    Write-Host ("[{0}] {1}  net={2}ms loss={3}% jit={4}ms  dns={5}ms  sig={6}% {7}" -f `
      $tickStart.ToString('HH:mm:ss'), $state.PadRight(4), $tick.'1.1.1.1', $loss, $jit, $tick.dns, $w.sig, $(if($w.band){$w.band}else{''}))
  }

  # wait for next tick, polling for Q
  $deadline = $tickStart.AddSeconds($IntervalSec)
  while ((Get-Date) -lt $deadline) {
    if ($interactive) {
      try {
        if ([Console]::KeyAvailable) {
          $key = [Console]::ReadKey($true)
          if ($key.Key -eq 'Q') { $stopReq = $true; break }
        }
      } catch {}
    }
    Start-Sleep -Milliseconds 150
  }
}

